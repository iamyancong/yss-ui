#!/usr/bin/env node

/**
 * AI 规则产物生成与检查脚本。
 *
 * 从 packages/skills/rules/ 单一源生成：
 * 1. AGENTS.md（marker-block 注入）
 * 2. .cursorrules
 * 3. .cursor/rules/rule.mdc
 *
 * 用法：
 *   node scripts/build-ai-rules.mjs [--check] [--root <dir>]
 */

import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { createRequire } from 'node:module';

const __filename = fileURLToPath(import.meta.url);
const __dirname = path.dirname(__filename);
const DEFAULT_ROOT = path.resolve(__dirname, '../..');

const require = createRequire(import.meta.url);
const { loadRulesSource, renderTarget, applyMarkerBlock } = require('../../packages/skills-cli/lib/ai-rules.js');

export const AUTO_GENERATED_HEADER =
  '<!-- AUTO-GENERATED by scripts/build-ai-rules.mjs from packages/skills/rules/ — DO NOT EDIT. Run: pnpm build:ai-rules -->';

export const AGENTS_MD_HEADER =
  '<!-- AUTO-GENERATED by scripts/build-ai-rules.mjs from packages/skills/rules/core.md — 标记块内勿手改，块外内容可自由编辑 -->';

export const REPO_ARTIFACTS = [
  {
    path: 'AGENTS.md',
    target: 'agents-md',
    mode: 'marker-block',
    header: AGENTS_MD_HEADER,
  },
  {
    path: '.cursorrules',
    target: 'mcp-codegen',
    header: AUTO_GENERATED_HEADER,
  },
  {
    path: '.cursor/rules/rule.mdc',
    target: 'mcp-codegen',
    frontmatter: { alwaysApply: true, title: 'YSS UI 代码生成规范' },
    header: AUTO_GENERATED_HEADER,
  },
];

/**
 * 执行规则生成或变更检查。
 *
 * @param {{ root?: string, check?: boolean }} [options] 选项
 * @returns {{ changed: string[] }} 存在变动的文件相对路径清单
 */
export function buildAiRules(options = {}) {
  const rootDir = path.resolve(options.root || DEFAULT_ROOT);
  const isCheck = Boolean(options.check);
  const rulesDir = path.join(rootDir, 'packages/skills/rules');

  const rulesSource = loadRulesSource(rulesDir);
  const changed = [];

  for (const artifact of REPO_ARTIFACTS) {
    const destPath = path.join(rootDir, artifact.path);
    const fileExists = fs.existsSync(destPath);
    const currentContent = fileExists ? fs.readFileSync(destPath, 'utf8') : null;

    let expectedContent;
    if (artifact.mode === 'marker-block') {
      const renderedBlock = renderTarget(artifact.target, rulesSource, {
        header: artifact.header,
        frontmatter: artifact.frontmatter,
      });
      const existing = currentContent || '';
      try {
        expectedContent = applyMarkerBlock(existing, renderedBlock, rulesSource.config.marker);
      } catch (err) {
        throw new Error(`处理 ${artifact.path} 的 marker-block 失败: ${err.message}`);
      }
    } else {
      expectedContent = renderTarget(artifact.target, rulesSource, {
        header: artifact.header,
        frontmatter: artifact.frontmatter,
      });
    }

    if (!fileExists || currentContent !== expectedContent) {
      changed.push(artifact.path);
      if (!isCheck) {
        fs.mkdirSync(path.dirname(destPath), { recursive: true });
        fs.writeFileSync(destPath, expectedContent, 'utf8');
        console.log(`[build-ai-rules] updated: ${artifact.path}`);
      }
    } else if (!isCheck) {
      console.log(`[build-ai-rules] unchanged: ${artifact.path}`);
    }
  }

  return { changed };
}

function parseCliArgs(args) {
  let isCheck = false;
  let rootDir = DEFAULT_ROOT;

  for (let i = 0; i < args.length; i++) {
    const arg = args[i];
    if (arg === '--check') {
      isCheck = true;
    } else if (arg === '--root' && i + 1 < args.length) {
      rootDir = args[++i];
    }
  }

  return { check: isCheck, root: rootDir };
}

function main() {
  const { check, root } = parseCliArgs(process.argv.slice(2));

  try {
    const { changed } = buildAiRules({ check, root });

    if (check) {
      if (changed.length > 0) {
        console.error('❌ AI 规则产物与源文件不一致，以下文件存在差异或缺失:');
        for (const file of changed) {
          console.error(`  - ${file}`);
        }
        console.error('\n请在仓库根目录执行: pnpm build:ai-rules 重新生成并纳入提交。');
        process.exit(1);
      } else {
        console.log('✅ AI 规则产物检查通过，所有生成文件与源保持一致。');
      }
    } else {
      console.log(`✨ AI 规则生成完成（变动: ${changed.length} 项）。`);
    }
  } catch (err) {
    console.error(`❌ 执行失败: ${err.message}`);
    process.exit(1);
  }
}

const isMain = process.argv[1] && (path.resolve(process.argv[1]) === path.resolve(__filename) || path.resolve(process.argv[1]) === path.resolve(__dirname, '../build-ai-rules.mjs'));
if (isMain) {
  main();
}
