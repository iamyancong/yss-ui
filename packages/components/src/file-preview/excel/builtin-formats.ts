/** 内置编号对应的格式代码；未知编号按 General 处理 */
export function builtinFormat(id: number, locale = 'zh-CN'): string {
  const lang = locale.toLowerCase();
  const local = lang.startsWith('zh') ? (/tw|hk|hant/.test(lang) ? TW : ZH) : EN;
  return local[id] ?? COMMON[id] ?? CJK_DATE[id] ?? 'General';
}
